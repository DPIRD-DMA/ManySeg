def source_dir(raw: Path) -> Path:
    raw = Path(raw)
    for cand in (raw, raw.parent / "ai4boundaries" / "sentinel2"):
        if (cand / "masks.zip").exists():
            return cand
    raise FileNotFoundError(f"no masks.zip in {raw} or ../ai4boundaries/sentinel2")


def _relabel(ids: np.ndarray) -> np.ndarray:
    ids = np.nan_to_num(ids, nan=-10000)
    ids = np.where(ids > 0, ids, 0).astype(np.int64)
    u, inv = np.unique(ids, return_inverse=True)
    return (inv.reshape(ids.shape) + (0 if u[0] == 0 else 1)).astype(np.int32)


def _read(args):
    import h5py
    import tifffile

    src, split, name = args
    with zipfile.ZipFile(src / f"{split}.zip") as z, \
            h5py.File(io.BytesIO(z.read(f"{split}/{name}_S2_10m_256.nc")), "r") as f:
        img = np.stack([f[b][()] for b in BANDS], axis=-1).astype(np.float32)  # T H W C
        days = f["time"][()].astype(np.float32)
    img[img == 0] = np.nan
    with zipfile.ZipFile(src / "masks.zip") as z:
        # masks.zip uses the image's name; the FTP URLs use "_S2label_"
        names = set(z.namelist())
        member = next(f"{split}/{name}_{tag}_10m_256.tif" for tag in ("S2", "S2label")
                      if f"{split}/{name}_{tag}_10m_256.tif" in names)
        m = tifffile.imread(io.BytesIO(z.read(member)))
    seq = _relabel(m[..., 3])
    agree = float(((m[..., 0] > 0.5) == (seq > 0)).mean())
    valid = np.isfinite(img).mean(axis=(1, 2)).min(axis=1) >= 0.5  # every band half present
    return img / 1e4, seq, days, valid, agree


def _bounded_map(ex, fn, jobs, chunk: int = 64):
    """``ex.map`` in chunks: at most ``chunk`` decoded results are held at once."""
    for s in range(0, len(jobs), chunk):
        yield from ex.map(fn, jobs[s:s + chunk])


def prepare(raw: Path, cache: Path, workers: int = 4, expected: dict | None = EXPECTED,
            **_) -> dict:
    from numpy.lib.format import open_memmap

    src, cache = source_dir(raw), Path(cache)
    cache.mkdir(parents=True, exist_ok=True)
    summary, stats = {}, {}
    for split in ("train", "val", "test"):
        names = sorted(line.split(",")[0].replace("_S2_10m_256.nc", "")
                       for line in (src / f"{split}.csv").read_text().splitlines()[1:]
                       if line.strip())
        if expected is not None and len(names) != expected[split]:
            raise RuntimeError(f"integrity: {split} lists {len(names)}, expected "
                               f"{expected[split]}")
        n = len(names)
        imgs = open_memmap(cache / f"{split}_images.s2.npy", "w+", np.float16,
                           (n, T, SIZE, SIZE, len(BANDS)))
        masks = open_memmap(cache / f"{split}_masks.npy", "w+", np.int32, (n, SIZE, SIZE))
        dates = np.empty((n, T), np.float32)
        valid = np.empty((n, T), bool)
        agree = []
        with ProcessPoolExecutor(workers) as ex:
            jobs = [(src, split, nm) for nm in names]
            for j, (im, m, d, v, a) in enumerate(_bounded_map(ex, _read, jobs)):
                if im.shape != (T, SIZE, SIZE, len(BANDS)) or d.shape != (T,):
                    raise RuntimeError(f"integrity: {names[j]} has shape {im.shape}")
                imgs[j], masks[j], dates[j], valid[j] = im, m, d, v
                agree.append(a)
        imgs.flush()
        masks.flush()
        np.save(cache / f"{split}_dates.npy", dates)
        np.save(cache / f"{split}_valid.npy", valid)
        (cache / f"{split}_names.json").write_text(json.dumps(names))
        if split == "train":
            flat = imgs.reshape(n * T, SIZE, SIZE, len(BANDS))
            stats["mean"], stats["std"] = (
                {"s2": v} for v in channel_stats(flat, chunk=64))
        summary[split] = {"n": n, "extent_agreement": float(np.mean(agree)),
                          "invalid_dates": int((~valid).sum()),
                          "date_days": dates[0].tolist()}
        if min(agree) < 0.95:
            raise RuntimeError(f"integrity: published extent disagrees with field ids on "
                               f"{split} (min {min(agree):.3f})")
        del imgs, masks
    (cache / "meta.json").write_text(json.dumps({**stats, "summary": summary}, indent=1))
    return summary


def series_extras(cache: Path, split_name: str) -> dict[str, np.ndarray]:
    return {"s2_dates": np.load(Path(cache) / f"{split_name}_dates.npy"),
            "s2_mask": np.load(Path(cache) / f"{split_name}_valid.npy").astype(np.float32)}


def single_date(split):
    split.images = {k: np.asarray(v[:, SINGLE_INDEX]) for k, v in split.images.items()}
    return split


