"""AI4Boundaries, Sentinel-2 subset (d'Andrimont et al. 2023). Licence: CC BY 4.0, (c) EU.

Field delineation (boundary + distance instances) from a time series: 256x256 tiles at 10 m
(EPSG:3035) from seven regions (AT, ES-Catalonia, FR, LU, NL, SE, SI); six monthly composites,
March to August 2019, bands B2, B3, B4, B8 (NDVI is also published; it is derived from B4/B8
and left out). Labels: 2019 GSAA parcels, ``*_S2label_10m_256.tif`` with the same four bands as
the orthophoto subset (extent, boundary, distance, field enumeration); as there, only the field
enumeration is kept and targets are generated by ``manyseg.instances``.

Raw data (``raw/ai4boundaries/sentinel2``): ``train.zip`` / ``val.zip`` / ``test.zip`` of NetCDF
files and ``masks.zip``, read in place. Splits: official, 5,319 / 1,140 / 1,139 (random, not
spatially blocked; names keep the country prefix).

Preprocessing: digital numbers / 1e4 as float16, fill value 0 -> NaN (zero after
normalisation); per-band mean/std from train; ``<split>_dates.npy`` = days since 2019-03-01;
``<split>_valid.npy`` = per-date validity (every band at least half present).

Variants (cache ``ai4boundaries_s2``): ``ai4boundaries_s2`` (series ``s2`` with ``s2_dates`` and
``s2_mask``) and ``ai4boundaries_s2_single`` (the July composite, ``SINGLE_INDEX``, as an
ordinary raster).
"""

