"""E028 analysis: tables (mean ± SD over seeds of tile means) and the pre-registered decisions.

    uv run python experiments/E028_vector_oracle/analyze.py [--tag ""]
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
AREAS = ("murdoch", "northam")
LEVELS = ("L0", "L1", "L2", "L3")
FACTOR_CONDS = ("only_occ", "only_blur", "only_noise", "only_miss", "only_vec")
ROAD_METRICS = ("apls", "geo_f1", "junction_f1")
BLD_METRICS = ("ciou", "det_f1", "miou", "n_ratio", "polis")


def seed_values(rows, metric):
    """{(area, rep, cond): array over seeds of the mean over tiles}."""
    acc = defaultdict(lambda: defaultdict(list))
    for r in rows:
        v = r.get(metric)
        if v is None or (isinstance(v, float) and np.isnan(v)):
            continue
        acc[(r["area"], r["rep"], r["cond"])][r["seed"]].append(v)
    return {k: np.array([np.mean(v) for _, v in sorted(s.items())]) for k, s in acc.items()}


def fmt(x: np.ndarray) -> str:
    return f"{x.mean():.3f} ± {x.std(ddof=1):.3f}" if len(x) > 1 else f"{x.mean():.3f}"


def beats(sv, a, b, cond) -> bool:
    for area in AREAS:
        xa, xb = sv[(area, a, cond)], sv[(area, b, cond)]
        diff = xa.mean() - xb.mean()
        pooled = np.sqrt((xa.var(ddof=1) + xb.var(ddof=1)) / 2)
        if not (diff > 2 * pooled and diff >= 0.02):
            return False
    return True


def matches(sv, a, b, cond) -> bool:
    return all(sv[(area, a, cond)].mean() >= sv[(area, b, cond)].mean() - 0.02 for area in AREAS)


def matches_best(sv, a, others, cond) -> bool:
    return all(sv[(area, a, cond)].mean() >= max(sv[(area, o, cond)].mean() for o in others) - 0.02
               for area in AREAS)


def table(sv, reps, conds, title) -> list[str]:
    out = [f"\n**{title}**\n", "| area | rep | " + " | ".join(conds) + " |",
           "|---|---|" + "---|" * len(conds)]
    for area in AREAS:
        for rep in reps:
            cells = [fmt(sv[(area, rep, c)]) if (area, rep, c) in sv else "" for c in conds]
            out.append(f"| {area} | {rep} | " + " | ".join(cells) + " |")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default="")
    args = ap.parse_args()
    rows = [json.loads(line) for line in (HERE / "runs" / f"test{args.tag}.jsonl").open()]
    roads = [r for r in rows if r["task"] == "roads"]
    blds = [r for r in rows if r["task"] == "buildings"]
    lines = ["## Results (generated by analyze.py)"]
    for m in ROAD_METRICS:
        lines += table(seed_values(roads, m), ("R0", "R1", "R2"), LEVELS, f"Roads: {m}")
    for m in BLD_METRICS:
        lines += table(seed_values(blds, m), ("B0", "B1", "B2"), LEVELS, f"Footprints: {m}")
    lines += table(seed_values(roads, "apls"), ("R0", "R1", "R2"), FACTOR_CONDS,
                   "Roads APLS, one corruption family at its level-2 setting (level-2 parameters)")
    lines += table(seed_values(blds, "ciou"), ("B0", "B1", "B2"), FACTOR_CONDS,
                   "Footprints C-IoU, one corruption family at its level-2 setting (level-2 parameters)")

    # crossings: GT grade-separated crossings with predicted road nearby and no false junction
    lines.append("\n**Road crossings (bridges / overpasses), all seeds pooled.** Registered metric: GT "
                 "crossings with no predicted junction within 8 m, of all crossings (a missing road also "
                 "counts). Added (amendment 2): the same among crossings with predicted road within 5 m.\n")
    lines += ["| area | rep | " + " | ".join(LEVELS) + " |", "|---|---|" + "---|" * len(LEVELS)]
    for area in AREAS:
        for rep in ("R0", "R1", "R2"):
            cells = []
            for c in LEVELS:
                rr = [r for r in roads if r["area"] == area and r["rep"] == rep and r["cond"] == c]
                nj, ok, cov, n = (sum(r[k] for r in rr) for k in ("cross_nojunc", "cross_ok", "cross_cov", "cross_n"))
                cells.append(f"{nj}/{n}; {ok}/{cov} covered" if n else "–")
            lines.append(f"| {area} | {rep} | " + " | ".join(cells) + " |")

    # encoding loss of the graph tensor (level 0 rows carry it; identical across seeds)
    for rep in ("R2", "B2"):
        rr = [r for r in rows if r["rep"] == rep and r["cond"] == "L0" and r["seed"] == 0]
        u, e = sum(r.get("unrepresented", 0) for r in rr), sum(r.get("ends", 0) for r in rr)
        lines.append(f"\n{rep} encoding: {u} of {e} edge ends found no free sector ({u / max(e, 1):.2%}).")

    # decisions
    ap_, ci, df = seed_values(roads, "apls"), seed_values(blds, "ciou"), seed_values(blds, "det_f1")
    lines.append("\n## Decisions (pre-registered rules)\n")
    for rep in ("R2", "R1"):
        b = [c for c in ("L1", "L2") if beats(ap_, rep, "R0", c)]
        ok = bool(b) and matches(ap_, rep, "R0", "L0")
        lines.append(f"* Roads: {rep} beats R0 (APLS) at {b or 'neither L1 nor L2'}; matches at L0: "
                     f"{matches(ap_, rep, 'R0', 'L0')} → **{'include' if ok else 'drop'} {rep} in stage 1**.")
    b = [c for c in ("L1", "L2") if beats(ci, "B1", "B0", c)]
    mf = all(matches(df, "B1", "B0", c) for c in ("L0", "L1", "L2"))
    lines.append(f"* Corner heatmap: B1 beats B0 (C-IoU) at {b or 'neither L1 nor L2'}; matches B0 detection "
                 f"F1 at L0–L2: {mf} → **{'include' if b and mf else 'drop'} B1 in stage 2**.")
    per = {c: (matches_best(ci, "B2", ("B0", "B1"), c), matches_best(df, "B2", ("B0", "B1"), c))
           for c in ("L0", "L1", "L2")}
    viable = all(a and b for a, b in per.values())
    lines.append(f"* Unification: B2 matches the better of B0/B1 (C-IoU, det F1) per level: {per} → "
                 f"**{'viable' if viable else 'not viable'}**.")
    text = "\n".join(lines)
    (HERE / "runs" / f"results{args.tag}.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
