"""Generate docs/backbone_compatibility.md by probing timm models in isolated subprocesses.

Usage: uv run python scripts/backbone_compat.py [--jobs 3] [--timeout 300] [models...]
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import timm
import torch

MODELS = [
    # CNNs
    "resnet18", "resnet50", "resnet50d", "resnext50_32x4d", "seresnext26d_32x4d",
    "efficientnet_b0", "efficientnet_b3", "tf_efficientnetv2_s", "convnext_tiny",
    "convnextv2_tiny", "edgenext_small", "mobilenetv3_large_100", "mobilenetv4_conv_small",
    "regnetx_032", "regnety_016", "ghostnetv2_100", "rexnet_100", "densenet121", "vgg16_bn",
    "dla34", "cspdarknet53", "hrnet_w18_small", "inception_next_tiny", "repvit_m1",
    # hierarchical transformers / hybrids
    "swin_tiny_patch4_window7_224", "swinv2_tiny_window8_256", "pvt_v2_b1",
    "maxvit_tiny_tf_224", "coatnet_0_rw_224", "fastvit_t12", "efficientformerv2_s0",
    "levit_128s", "hiera_tiny_224", "mambaout_tiny", "caformer_s18", "poolformerv2_s12",
    "nextvit_small", "focalnet_tiny_srf", "davit_tiny", "efficientvit_b1",
    # plain ViTs
    "vit_small_patch16_224", "vit_base_patch16_224", "deit3_small_patch16_224",
    "vit_small_patch14_dinov2", "eva02_small_patch14_224", "vit_base_patch16_siglip_224",
]


def probe_one(name: str, timeout: int) -> dict:
    code = ("import json,sys,torch; torch.set_num_threads(4); "
            "from manyseg.backbones.capabilities import probe_backbone; "
            f"print('@@'+json.dumps(probe_backbone({name!r}, export=True).to_dict()))")
    try:
        r = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True,
                           timeout=timeout)
    except subprocess.TimeoutExpired:
        return {"name": name, "buildable": None, "error": f"timeout after {timeout}s"}
    for line in r.stdout.splitlines():
        if line.startswith("@@"):
            return json.loads(line[2:])
    return {"name": name, "buildable": False, "error": (r.stderr or "no output")[-200:]}


def render(rows: list[dict]) -> str:
    out = [
        "# Backbone compatibility (generated)",
        "",
        f"Generated by `scripts/backbone_compat.py` with timm {timm.__version__}, "
        f"torch {torch.__version__}. Random weights; U-Net decoder; probe sizes 64x64, "
        "97x131 (odd), 160x96. `export` = `manyseg.export.export_model` (dynamic H/W, "
        "deferred runtime asserts), checked against eager at an unseen size.",
        "",
        "| model | builds | strides | native layout | plain ViT | sizes | export (dynamic) | "
        "params (M) | notes |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        if not r.get("buildable"):
            out.append(f"| {r['name']} | no | | | | | | | {r.get('error', '')[:120]} |")
            continue
        out.append(
            f"| {r['name']} | yes | {','.join(map(str, r['feature_strides']))} | "
            f"{r['native_layout']} | {'yes' if r['plain_vit'] else ''} | {r['size_support']} | "
            f"{r['export_dynamic']} | {r['params_m']} | "
            f"{r['error'][:120] if r['size_support'] != 'any' else ''} |")
    n_any = sum(1 for r in rows if r.get("size_support") == "any")
    out += ["", f"{n_any}/{len(rows)} models support arbitrary input sizes end to end."]
    n_fixed = sum(1 for r in rows if r.get("size_support") == "fixed")
    if n_fixed:
        out += [f"The {n_fixed} `fixed` models are detected at construction "
                "(`TimmBackbone.fixed_size` = native size), so inputs up to that size work via "
                "padding; for larger inputs rebuild with `backbone_kwargs={\"img_size\": (H, W)}`."]
    out += [""]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("models", nargs="*")
    ap.add_argument("--jobs", type=int, default=3)
    ap.add_argument("--timeout", type=int, default=300)
    ap.add_argument("--out", default="docs/backbone_compatibility.md")
    a = ap.parse_args()
    names = a.models or MODELS
    with ThreadPoolExecutor(a.jobs) as ex:
        rows = list(ex.map(lambda n: probe_one(n, a.timeout), names))
    for r in rows:
        print(r["name"], r.get("size_support"), r.get("export_dynamic"), r.get("error", "")[:80],
              flush=True)
    Path(a.out).write_text(render(rows))
    Path(a.out).with_suffix(".json").write_text(json.dumps(rows, indent=1))


if __name__ == "__main__":
    main()
